const assert = require('node:assert/strict');
const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1000}});
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(process.env.BASE_URL || 'http://127.0.0.1:8765');
    const ids = await page.evaluate(() => {
      const s = OneRingStore;
      const heroes = ['Frodo','Gimli'].map(name => {const h=s.saveHero({id:name==='Gimli' ? 'x"><img src=x onerror=alert(1)>' : 'frodo',name,hope:8,maxHope:10});s.addHero(h.id);return h.id;});
      const enemy=s.addEnemy({name:'Ork',kind:'Ork',endurance:8,maxEndurance:8}).id;
      s.setMap(OneRingMap.generateTerrain('clearing','medium','sheet'));
      return {heroes,enemy};
    });
    await page.locator('[data-tab="map"]').click();
    const select = id => page.locator('.map-token').evaluateAll((nodes, id) => nodes.find(node => node.dataset.id === id).click(), id);
    const sheet = page.locator('#map-hero-sheet');
    const openAll = () => sheet.locator('details').evaluateAll(nodes => nodes.forEach(node => { node.open = true; }));
    const assertExpanded = async () => assert.equal(await sheet.locator('details[open]').count(),5);
    assert.equal(await sheet.isVisible(),false);
    await select('hero:'+ids.heroes[0]);
    assert.equal(await sheet.locator('details').count(),5);
    assert.equal(await sheet.locator('details[open]').count(),0);
    assert.equal(await sheet.locator('[data-hero-action]').count(),0);
    await sheet.locator('.sheet-character > summary').click();
    await sheet.locator('[name="shadowScars"]').fill('2');
    await sheet.locator('[name="shadowScars"]').blur();
    assert.equal(await sheet.locator('[name="shadow"]').inputValue(),'2');
    assert.equal(await sheet.locator('[name="shadow"]').getAttribute('min'),'2');
    await sheet.locator('[name="shadow"]').fill('1');
    await sheet.locator('[name="shadow"]').blur();
    assert.equal(await sheet.locator('[name="shadow"]').inputValue(),'2');
    await sheet.locator('[name="hope"]').fill('5');
    await sheet.locator('[name="hope"]').blur();
    assert.equal(await page.evaluate(id => OneRingStore.getState().heroes.find(h=>h.id===id).hope,ids.heroes[0]),5);
    assert.match(await page.locator('#map-panel').textContent(),/5\s*\/\s*10/);
    await page.evaluate(id => OneRingStore.saveHero({id,hope:4}), ids.heroes[0]);
    assert.equal(await sheet.locator('[name="hope"]').inputValue(),'4');
    assert.equal(await sheet.locator('.sheet-character').evaluate(node => node.open),true);
    await openAll();
    await select('hero:'+ids.heroes[0]);
    assert.equal(await sheet.locator('details[open]').count(),5);
    // Invalid drafts survive selecting another hero and are never written to it.
    await sheet.locator('[name="hope"]').fill('-1');
    await sheet.locator('[name="hope"]').blur();
    await select('hero:'+ids.heroes[1]);
    await assertExpanded();
    assert.equal(await sheet.locator('[name="name"]').inputValue(),'Gimli');
    assert.equal(await sheet.locator('img').count(),0);
    assert.equal(await sheet.locator('[name="hope"]').inputValue(),'8');
    await openAll();
    await select('hero:'+ids.heroes[0]);
    await assertExpanded();
    assert.equal(await sheet.locator('[name="hope"]').inputValue(),'-1');
    await sheet.locator('[name="hope"]').fill('3');
    await sheet.locator('[name="hope"]').blur();
    await openAll();
    await page.locator('.map-cycle-next').click();
    await assertExpanded();
    assert.equal(await sheet.locator('[name="name"]').inputValue(),'Gimli');
    await openAll();
    await page.locator('.map-cycle-prev').click();
    await assertExpanded();
    assert.equal(await sheet.locator('[name="name"]').inputValue(),'Frodo');
    await openAll();
    await select(ids.enemy);
    assert.equal(await sheet.isVisible(),false);
    await select('hero:'+ids.heroes[0]);
    await assertExpanded();
    // Removing the selected participant clears selection but preserves its cached draft.
    await openAll();
    await page.evaluate(id => OneRingStore.removeParticipant('hero:'+id), ids.heroes[0]);
    assert.equal(await sheet.isVisible(),false);
    await page.evaluate(id => OneRingStore.addHero(id), ids.heroes[0]);
    await select('hero:'+ids.heroes[0]);
    await assertExpanded();
    await page.locator('[data-tab="heroes"]').click();
    assert.equal(await page.locator('#hero-editor [name="hope"]').inputValue(),'3');
    assert.equal(await page.locator('#hero-editor [name="shadow"]').inputValue(),'2');
    await page.locator('#hero-editor [name="shadowScars"]').fill('4');
    await page.locator('#hero-editor [name="shadowScars"]').blur();
    assert.equal(await page.locator('#hero-editor [name="shadow"]').inputValue(),'4');
    assert.equal(await page.locator('#hero-editor [name="shadow"]').getAttribute('min'),'4');
    await page.locator('#hero-editor [name="shadow"]').fill('0');
    await page.locator('#hero-editor [name="shadow"]').blur();
    assert.equal(await page.locator('#hero-editor [name="shadow"]').inputValue(),'4');
    const duplicates = await page.evaluate(() => {const ids=[...document.querySelectorAll('[id]')].map(n=>n.id);return ids.filter((id,i)=>ids.indexOf(id)!==i);});
    assert.deepEqual(duplicates,[]);
    await page.locator('[data-tab="map"]').click();
    await page.setViewportSize({width:390,height:844});
    await sheet.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await page.screenshot({path:'/tmp/map-hero-sheet.png',fullPage:true});
    await page.evaluate(()=>OneRingStore.clearEncounter());
    assert.equal(await sheet.isVisible(),false);
    assert.deepEqual(errors,[]);
    console.log('Map hero sheet passed');
  } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
